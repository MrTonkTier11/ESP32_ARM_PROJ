#!/usr/bin/env python3
"""
build_web_assets.py
Reads WebHostControl/index.html, style.css, and script.js,
and generates include/web_assets.h containing PROGMEM raw string literals.
This provides a seamless offline fallback so the ESP32 web interface
always functions out-of-the-box, with or without LittleFS filesystem uploads.
"""

import os
from pathlib import Path

def main():
    proj_dir = Path(__file__).resolve().parent.parent
    web_dir = proj_dir / "WebHostControl"
    include_dir = proj_dir / "include"
    output_file = include_dir / "web_assets.h"

    index_html_path = web_dir / "index.html"
    style_css_path = web_dir / "style.css"
    script_js_path = web_dir / "script.js"

    if not index_html_path.exists():
        raise FileNotFoundError(f"Missing {index_html_path}")
    if not style_css_path.exists():
        raise FileNotFoundError(f"Missing {style_css_path}")
    if not script_js_path.exists():
        raise FileNotFoundError(f"Missing {script_js_path}")

    index_html = index_html_path.read_text(encoding="utf-8")
    style_css = style_css_path.read_text(encoding="utf-8")
    script_js = script_js_path.read_text(encoding="utf-8")

    header_content = f"""// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// Generated by tools/build_web_assets.py from WebHostControl/
// Provides PROGMEM fallback so the Web GUI always works without LittleFS upload.

#ifndef WEB_ASSETS_H
#define WEB_ASSETS_H

#include <Arduino.h>
#include <pgmspace.h>

static const char INDEX_HTML[] PROGMEM = R"rawliteral(
{index_html}
)rawliteral";

static const char STYLE_CSS[] PROGMEM = R"rawliteral(
{style_css}
)rawliteral";

static const char SCRIPT_JS[] PROGMEM = R"rawliteral(
{script_js}
)rawliteral";

#endif // WEB_ASSETS_H
"""

    include_dir.mkdir(parents=True, exist_ok=True)
    output_file.write_text(header_content, encoding="utf-8")
    print(f"Successfully generated {output_file} from {web_dir}")

if __name__ == "__main__":
    main()
